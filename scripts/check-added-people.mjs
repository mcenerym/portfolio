import assert from 'node:assert/strict';
import {people,validateNewPerson,validateCustomPeople,searchPeople,validateStoredState,validatePersonNotes,findFirstAvailable,validateAppointment,reminderPreview} from '../src/appointment-data.js';
const person={id:'AC-1010',name:'Alex Morgan',email:'alex@example.com',phone:'202-555-0123',color:'mint'};
const directory=[...people,person];
assert.equal(validateNewPerson(person),'');
assert.ok(validateNewPerson({...person,name:' '}));
assert.ok(validateNewPerson({...person,email:'bad'}));
assert.ok(validateNewPerson({...person,email:'',phone:''}));
assert.ok(validateNewPerson({...person,phone:'abc'}));
assert.equal(validateNewPerson({...person,email:''}),'');
assert.equal(validateNewPerson({...person,phone:''}),'');
assert.ok(validateCustomPeople([person]));
assert.ok(!validateCustomPeople([person,person]));
assert.ok(!validateCustomPeople([{...person,id:people[0].id}]));
assert.equal(searchPeople('alex',directory)[0].id,person.id);
const details={personId:person.id,procedureIds:['consult'],fromDate:'2026-10-28'};
const opening=findFirstAvailable([],details,new Date(2026,9,27,8),directory);
assert.ok(opening);
const appointment={id:'added-person-visit',...opening,personId:person.id,procedureIds:['consult'],status:'Scheduled'};
assert.equal(validateAppointment(appointment,[],'2026-10-27',directory),'');
assert.equal(reminderPreview(appointment,'email',directory).destination,person.email);
assert.equal(reminderPreview(appointment,'sms',directory).destination,person.phone);
const state=JSON.parse(JSON.stringify({customPeople:[person],appointments:[appointment],reminders:[],notesByPerson:{[person.id]:[{id:'note',text:'Test note',createdAt:'2026-10-27T12:00:00Z'}]}}));
assert.ok(validateStoredState(state));
assert.ok(validatePersonNotes(state.notesByPerson,directory));
assert.ok(!validateStoredState({...state,customPeople:[]}));
assert.ok(validateStoredState({appointments:[],reminders:[]}));
console.log('Passed: person validation, contact methods, duplicate IDs, search, availability, scheduling, reminders, notes and storage round-trip; older saved data remains compatible.');
